            'input[type="text"]',
            function () {

                isPemeriksaanFisikDirty = true;

            }
        );


        // ==========================================================
        // BLUR TEXT
        // ==========================================================

        $form.on(
            'blur',
            'input[type="text"]',
            function () {

                if (!isPemeriksaanFisikDirty) {
                    return;
                }

                simpanPemeriksaanFisikObs();

                isPemeriksaanFisikDirty = false;

            }
        );


        // ==========================================================
        // CHECKBOX
        // ==========================================================

        $form.on(
            'change',
            'input[type="checkbox"]',
            function (e) {

                // Jangan simpan ketika GET sedang mengisi form
                if (!e.originalEvent) {
                    return;
                }


                const name =
                    $(this).attr('name');


                // Hanya satu pilihan dalam satu kelompok
                $form
                    .find(`input[type="checkbox"][name="${name}"]`)
                    .not(this)
                    .prop('checked', false);


                simpanPemeriksaanFisikObs();

            }
        );

    });

