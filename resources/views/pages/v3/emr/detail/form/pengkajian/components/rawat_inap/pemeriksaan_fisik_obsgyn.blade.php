    // ==============================================================
    // SIMPAN DATA
    // ==============================================================

    function simpanPemeriksaanFisikObs() {

        const $form =
            $('#form_pemeriksaan_fisik');


        const data = getFormDataByName(
            $form,
            {
                NOKUNJ: kunjungan
            }
        );


        $.ajax({

            url: `/api/v2/emr/pengkajian/ri/pemeriksaanfisikobsgyn/${kunjungan}/simpan`,

            type: 'POST',

            data: data,

            headers: {
                'X-CSRF-TOKEN':
                    $('meta[name="csrf-token"]').attr('content')
            },

            success: function (res) {

                // console.log(
                //     'Pemeriksaan Fisik Obsgyn berhasil disimpan.',
                //     res
                // );

            },

            error: function (xhr) {

                let message =
                    'Data gagal disimpan.';


                if (
                    xhr.status === 422 &&
                    xhr.responseJSON &&
                    xhr.responseJSON.errors
                ) {

                    message =
                        Object.values(
                            xhr.responseJSON.errors
                        )
                        .flat()
                        .join('&nbsp;');

                }

                else if (
                    xhr.responseJSON &&
                    xhr.responseJSON.message
                ) {

                    message =
                        xhr.responseJSON.message;

                }


                iziToast.error({

                    title: 'Validasi Gagal!',

                    message: message,

                    position: 'topRight'

                });

            }

        });

    }


