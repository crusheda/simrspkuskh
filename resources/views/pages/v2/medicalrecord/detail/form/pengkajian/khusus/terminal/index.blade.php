    // masih berjalan:
    //
    // request #1 sedang berjalan
    // user ubah field A -> pending
    // user ubah field B -> pending (payload terbaru menggantikan)
    // request #1 selesai
    // otomatis kirim payload terakhir
    // ==========================================================
    function sendData(data) {

        data.NOKUNJ = kunjungan;

        if (isDataSaving) {
            pendingSave = true;
            pendingData = data;
            return;
        }

        isDataSaving = true;

        $.ajax({
            url: `${baseUrl}/simpan`,
            type: 'POST',
            data: data,

            headers: {
                'X-CSRF-TOKEN': csrfToken
            },

            success: function (res) {
                lastSavedPayload = data;
            },

            error: function (xhr) {

                console.error(
                    'Data terminal gagal disimpan:',
                    xhr.responseText
                );

                let message = 'Data gagal disimpan.';

                if (
                    xhr.status === 422 &&
                    xhr.responseJSON?.errors
                ) {
                    message = Object
                        .values(xhr.responseJSON.errors)
                        .flat()
                        .join('<br>');
                } else if (xhr.responseJSON?.message) {
                    message = xhr.responseJSON.message;
                }

                if (typeof iziToast !== 'undefined') {
                    iziToast.error({
                        title: 'Gagal Menyimpan!',
                        message: message,
                        position: 'topRight'
                    });
                }
            },

            complete: function () {

                isDataSaving = false;

                if (pendingSave && pendingData) {

                    const nextData = pendingData;

                    pendingSave = false;
                    pendingData = null;

                    // Langsung kirim snapshot terbaru.
                    sendData(nextData);
                }
            }
        });
    }

    // ==========================================================
    // REQUEST SAVE
    // ==========================================================
    function requestSave() {

        if (isDataLoading) {
            return;
        }

        const data = buildPayload();

        // Tidak perlu request kalau payload sama dengan yang terakhir
        // berhasil disimpan, kecuali memang sedang menunggu request.
        if (
            !isDataSaving &&
            JSON.stringify(data) === JSON.stringify(lastSavedPayload)
        ) {
            return;
        }

        sendData(data);
    }

    // ==========================================================
    // SINGLE CHECKBOX
    //
    // Checkbox dengan name yang sama bertindak seperti radio:
    // hanya satu pilihan yang boleh aktif.
    // ==========================================================
    $form.on(
        'change.terminal',
        'input.single-checkbox',
        function () {

            if (isDataLoading) {
                return;
            }

            const name = $(this).attr('name');

            // Single checkbox harus bersifat single-choice
            if (this.checked && name) {

                $form
                    .find(`input.single-checkbox[name="${name}"]`)
                    .not(this)
                    .prop('checked', false);
            }

            // Update input yang bergantung pada pilihan ini
            FormHelper.updateDependentInputs($form);

            // Autosave
            requestSave();
        }
    );

    // ==========================================================
    // CHECKBOX BIASA
    // ==========================================================
    $form.on(
        'change.terminal',
        'input[type="checkbox"]:not(.single-checkbox), select, input[type="radio"]',
        function () {

            if (isDataLoading) {
                return;
            }

            requestSave();
        }
    );

    // ==========================================================
    // TEXT / NUMBER / TEXTAREA
    //
    // Save ketika user selesai mengedit dan keluar dari field.
    // Tidak ada SaveTimer / debounce timer.
    // ==========================================================
    $form.on(
        'blur.terminal',
        'input:not([type="checkbox"]):not([type="radio"]), textarea, select',
        function () {

            if (isDataLoading) {
                return;
            }

            requestSave();
        }
    );

    // ==========================================================
    // LOAD AWAL
    // ==========================================================
    getData();

})();
</script>
