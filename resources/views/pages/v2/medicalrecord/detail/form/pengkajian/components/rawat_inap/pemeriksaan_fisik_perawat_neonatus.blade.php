<script>
(function () {

    // ==========================================================
    // CONFIG
    // ==========================================================

    const $form = $('#form_pemeriksaan_fisik_perawat_neonatus');

    // KUNJUNGAN diambil dari route/page
    const KUNJUNGAN = '{{ $KUNJUNGAN ?? request()->route("KUNJUNGAN") }}';

    let isSaving = false;
    let savePending = false;


    // ==========================================================
    // GET DATA
    // ==========================================================

    function getPemeriksaanFisikNeonatus() {

        if (!$form.length) {
            console.warn(
                'Form Pemeriksaan Fisik Perawat Neonatus tidak ditemukan.'
            );
            return;
        }

        $.ajax({
            url: `/api/v2/emr/pengkajian/ri/pemeriksaanfisikneonatus/${kunjungan}`,
            type: 'GET',
            dataType: 'json',

            success: function (res) {

                if (!res.status) {
                    console.warn(
                        res.message || 'Data pemeriksaan fisik tidak ditemukan.'
                    );
                    return;
                }

                const data = res.data || {};

                // Normalisasi key menjadi lowercase
                const normalizedData = {};

                Object.keys(data).forEach(function (key) {
                    normalizedData[key.toLowerCase()] = data[key];
                });


                // ==================================================
                // ISI SEMUA FIELD BERDASARKAN NAME
                // ==================================================

                $form.find(
                    'input[name], textarea[name], select[name]'
                ).each(function () {

                    const $el = $(this);
                    const name = $el.attr('name');

                    if (!name) {
                        return;
                    }

                    const key = name.toLowerCase();

                    if (
                        !Object.prototype.hasOwnProperty.call(
                            normalizedData,
                            key
                        )
                    ) {
                        return;
                    }

                    const value = normalizedData[key];


                    // ==================================================
                    // CHECKBOX
                    // ==================================================

                    if ($el.is(':checkbox')) {

                        $el.prop(
                            'checked',
                            String($el.val()) === String(value)
                        );

                        return;
                    }


                    // ==================================================
                    // RADIO
                    // ==================================================

                    if ($el.is(':radio')) {

                        $el.prop(
                            'checked',
                            String($el.val()) === String(value)
                        );

                        return;
                    }


                    // ==================================================
                    // INPUT / TEXTAREA / SELECT
                    // ==================================================

                    $el.val(
                        value === null || value === undefined
                            ? ''
                            : value
                    );
                });

            },

            error: function (xhr) {

                console.error(
                    'Gagal mengambil Pemeriksaan Fisik Neonatus:',
                    xhr.responseJSON || xhr.responseText
                );

            }
        });
    }


    // ==========================================================
    // AMBIL DATA FORM
    // ==========================================================

    function getFormDataByName() {

        const data = {
            NOKUNJ: KUNJUNGAN
        };

        $form.find(
            'input[name], textarea[name], select[name]'
        ).each(function () {

            const $el = $(this);
            const name = $el.attr('name');

            if (!name) {
                return;
            }


            // ==================================================
            // CHECKBOX
            // ==================================================

            if ($el.is(':checkbox')) {

                /*
                 * Karena menggunakan single-checkbox,
                 * hanya checkbox yang terpilih yang disimpan.
                 */

                if ($el.is(':checked')) {
                    data[name] = $el.val();
                } else if (data[name] === undefined) {
                    data[name] = null;
                }

                return;
            }


            // ==================================================
            // RADIO
            // ==================================================

            if ($el.is(':radio')) {

                if ($el.is(':checked')) {
                    data[name] = $el.val();
                } else if (data[name] === undefined) {
                    data[name] = null;
                }

                return;
            }


            // ==================================================
            // INPUT / TEXTAREA / SELECT
            // ==================================================

            data[name] = $el.val();

        });

        return data;
    }


    // ==========================================================
    // SAVE DATA
    // ==========================================================

    function simpanPemeriksaanFisikNeonatus() {

        // ======================================================
        // JIKA MASIH ADA REQUEST
        // ======================================================

        if (isSaving) {

            savePending = true;

            console.log(
                'SAVE masih berjalan -> tandai sebagai pending.'
            );

            return;
        }


        isSaving = true;
        savePending = false;


        const data = getFormDataByName();


        $.ajax({

            url:
                `/api/v2/emr/pengkajian/ri/pemeriksaanfisikneonatus/${kunjungan}/simpan`,

            type: 'POST',

            data: data,

            headers: {

                'X-CSRF-TOKEN': $(
                    'meta[name="csrf-token"]'
                ).attr('content')

            },

            success: function (res) {

                if (res.status) {

                    console.log(
                        'Pemeriksaan Fisik Neonatus berhasil disimpan.'
                    );

                } else {

                    console.warn(
                        res.message ||
                        'Pemeriksaan Fisik Neonatus gagal disimpan.'
                    );

                }

            },

            error: function (xhr) {

                console.error(
                    'Gagal menyimpan Pemeriksaan Fisik Neonatus:',
                    xhr.responseJSON || xhr.responseText
                );

            },

            complete: function () {

                // ==================================================
                // BUKA LOCK
                // ==================================================

                isSaving = false;


                // ==================================================
                // ADA PERUBAHAN SAAT SAVE BERJALAN?
                // ==================================================

                if (savePending) {

                    console.log(
                        'Ada SAVE PENDING -> simpan data terbaru.'
                    );

                    savePending = false;

                    setTimeout(function () {
                        simpanPemeriksaanFisikNeonatus();
                    }, 0);
                }

            }

        });
    }


    // ==========================================================
    // SINGLE CHECKBOX
    // ==========================================================

    $(document).on(
        'change',
        '#form_pemeriksaan_fisik_perawat_neonatus .single-checkbox',
        function () {

            const name = $(this).attr('name');

            if (!name) {
                return;
            }

            /*
             * Hanya satu pilihan untuk setiap name.
             */

            if ($(this).is(':checked')) {

                $form
                    .find(
                        'input.single-checkbox[name="' + name + '"]'
                    )
                    .not(this)
                    .prop('checked', false);

            }

            simpanPemeriksaanFisikNeonatus();
        }
    );


    // ==========================================================
    // AUTO SAVE
    // ==========================================================

    $(function () {

        if (!$form.length) {
            console.warn(
                'Form Pemeriksaan Fisik Perawat Neonatus tidak ditemukan.'
            );
            return;
        }


        // ======================================================
        // LOAD DATA DAHULU
        // ======================================================

        getPemeriksaanFisikNeonatus();


        // ======================================================
        // TEXT / NUMBER / DATE / TIME / TEXTAREA
        // SAVE SAAT BLUR
        // ======================================================

        $form.on(
            'blur',
            'textarea, input:not([type="checkbox"]):not([type="radio"])',
            function () {

                simpanPemeriksaanFisikNeonatus();

            }
        );


        // ======================================================
        // SELECT
        // ======================================================

        $form.on(
            'change',
            'select',
            function () {

                simpanPemeriksaanFisikNeonatus();

            }
        );

    });

})();
</script>