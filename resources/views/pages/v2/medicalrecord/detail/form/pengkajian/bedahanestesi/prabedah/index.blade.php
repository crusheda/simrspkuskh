<script>
(function () {
    'use strict';

    const $form = $('#form_pra_bedah');

    let isDataLoading = false;
    let isDataSaving = false;

    // ==========================================================
    // GET DATA
    // ==========================================================
    function getData() {

        if (!$form.length) {
            console.warn('Form Data tidak ditemukan.');
            return;
        }

        isDataLoading = true;

        $.ajax({
            url: `/api/v2/emr/form/pengkajian/bedans/prabedah/${kunjungan}`,
            type: 'GET',
            dataType: 'json',

            success: function (res) {

                const tlt = res.data;

                if (!tlt) {
                    return;
                }

                setCheckboxValue(
                    'pb_ds_batuk',
                    tlt.BATUK
                );

                setCheckboxValue(
                    'pb_ds_pusing',
                    tlt.PUSING
                );

                setCheckboxValue(
                    'pb_ds_sesaknafas',
                    tlt.SESAKNAFAS
                );

                setCheckboxValue(
                    'pb_ds_pilek',
                    tlt.PILEK
                );

                setCheckboxValue(
                    'pb_ds_mual',
                    tlt.MUAL
                );

                setCheckboxValue(
                    'pb_ds_puasa',
                    tlt.PUASA
                );

                setCheckboxValue(
                    'pb_ds_gigipalsu',
                    tlt.GIGIPALSU
                );

                setCheckboxValue(
                    'pb_ds_lain',
                    tlt.LAIN
                );

                if (FormHelper.hasValue(tlt.LAIN_SEBUT)) {
                    FormHelper.setValue(
                        $form,
                        'pb_ds_lain_sebut',
                        tlt.LAIN_SEBUT
                    );
                }


                // ==========================================================
                // RIWAYAT OPERASI SEBELUMNYA
                // ==========================================================

                if (FormHelper.hasValue(tlt.ROS)) {
                    FormHelper.setValue(
                        $form,
                        'pb_ros',
                        tlt.ROS
                    );
                }


                // ==========================================================
                // DATA OBYEKTIF
                // ==========================================================

                if (FormHelper.hasValue(tlt.DO)) {
                    FormHelper.setValue(
                        $form,
                        'pb_do',
                        tlt.DO
                    );
                }


                // ==========================================================
                // RIWAYAT PENYAKIT
                // ==========================================================

                setCheckboxValue(
                    'pb_rp_dm',
                    tlt.DM
                );

                setCheckboxValue(
                    'pb_rp_tb',
                    tlt.TB
                );

                setCheckboxValue(
                    'pb_rp_hepatitis',
                    tlt.HEPATITIS
                );

                setCheckboxValue(
                    'pb_rp_hipertensi',
                    tlt.HIPERTENSI
                );

                setCheckboxValue(
                    'pb_rp_stemi',
                    tlt.STEMI
                );

                setCheckboxValue(
                    'pb_rp_hiv',
                    tlt.HIV
                );

                setCheckboxValue(
                    'pb_rp_asma',
                    tlt.ASMA
                );

                setCheckboxValue(
                    'pb_rp_chf',
                    tlt.CHF
                );

                setCheckboxValue(
                    'pb_rp_lain',
                    tlt.RP_LAIN
                );

                if (FormHelper.hasValue(tlt.RP_LAIN_SEBUT)) {
                    FormHelper.setValue(
                        $form,
                        'pb_rp_lain_sebut',
                        tlt.RP_LAIN_SEBUT
                    );
                }


                // ==========================================================
                // PEMERIKSAAN LAB / RAD
                // ==========================================================

                if (FormHelper.hasValue(tlt.LAB)) {
                    FormHelper.setValue(
                        $form,
                        'pb_lab',
                        tlt.LAB
                    );
                }

                if (FormHelper.hasValue(tlt.RAD)) {
                    FormHelper.setValue(
                        $form,
                        'pb_rad',
                        tlt.RAD
                    );
                }


                // ==========================================================
                // DATA PRA OPERASI
                // ==========================================================

                if (FormHelper.hasValue(tlt.DPO)) {
                    FormHelper.setValue(
                        $form,
                        'pb_dpo',
                        tlt.DPO
                    );
                }

                if (FormHelper.hasValue(tlt.PPDO)) {
                    FormHelper.setValue(
                        $form,
                        'pb_ppdo',
                        tlt.PPDO
                    );
                }

                if (FormHelper.hasValue(tlt.PRO)) {
                    FormHelper.setValue(
                        $form,
                        'pb_pro',
                        tlt.PRO
                    );
                }

                if (FormHelper.hasValue(tlt.PLO)) {
                    FormHelper.setValue(
                        $form,
                        'pb_plo',
                        tlt.PLO
                    );
                }

                if (FormHelper.hasValue(tlt.AK)) {
                    FormHelper.setValue(
                        $form,
                        'pb_ak',
                        tlt.AK
                    );
                }

                if (FormHelper.hasValue(tlt.RO)) {
                    FormHelper.setValue(
                        $form,
                        'pb_ro',
                        tlt.RO
                    );
                }
            },

            error: function (xhr, status, error) {

                console.error(
                    'Error :',
                    xhr.responseText || error
                );

                let message =
                    'Gagal mengambil data.';

                if (xhr.responseJSON?.message) {
                    message = xhr.responseJSON.message;
                }

                console.warn(message);
            },

            complete: function () {
                isDataLoading = false;
            }
        });
    }

    // ==========================================================
    // SIMPAN DATA
    // ==========================================================
    function simpanData() {

        if (
            !$form.length ||
            isDataLoading ||
            isDataSaving
        ) {
            return;
        }

        const data = getFormDataByName($form, {
            NOKUNJ: kunjungan
        });

        isDataSaving = true;

        $.ajax({
            url: `/api/v2/emr/form/pengkajian/bedans/prabedah/${kunjungan}/simpan`,
            type: 'POST',
            data: data,

            headers: {
                'X-CSRF-TOKEN': $(
                    'meta[name="csrf-token"]'
                ).attr('content')
            },

            success: function (res) {

            },

            error: function (xhr) {

                let message =
                    'Data gagal disimpan.';

                if (
                    xhr.status === 422 &&
                    xhr.responseJSON?.errors
                ) {
                    message = Object
                        .values(xhr.responseJSON.errors)
                        .flat()
                        .join('<br>');
                }
                else if (xhr.responseJSON?.message) {
                    message = xhr.responseJSON.message;
                }

                iziToast.error({
                    title: 'Validasi Gagal!',
                    message: message,
                    position: 'topRight'
                });
            },

            complete: function () {
                isDataSaving = false;
            }
        });
    }

    // ==========================================================
    // AUTO SAVE
    // ==========================================================
    $(function () {

        if (!$form.length) {
            return;
        }

        getData();

        $form.on(
            'blur',
            'textarea,input',
            function () {

                if (isDataLoading) {
                    return;
                }

                simpanData();
            }
        );

        $form.on(
            'change',
            'select,input[type="checkbox"],input[type="radio"]',
            function () {

                if (isDataLoading) {
                    return;
                }

                simpanData();
            }
        );
    });

    function setCheckboxValue(name, value) {

        const $checkbox = $form.find(
            `[name="${name}"]`
        );

        if (!$checkbox.length) {
            return;
        }

        $checkbox
            .prop('checked', Number(value) === 1)
            .trigger('change');
    }

})();
</script>
